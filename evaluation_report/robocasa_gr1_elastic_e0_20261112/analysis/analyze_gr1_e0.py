#!/usr/bin/env python3
"""Result tables of GR1-E0 (elastic distillation on RoboCasa-GR1), computed only from the evidence stored in this report.

Usage: python3 analyze_gr1_e0.py        (run from anywhere)
Reads   ../eval/eEE_<schedule>/n12/*.json and ../eval/eEE_<schedule>_validation.json  (25 student evaluations),
        ../training/metrics.jsonl.gz, ../training/launches.jsonl,
        ../../robocasa_gr1_continuation_20261108/eval/official_epoch{09,10}/n12/*.json  (teacher, same H100 protocol).
Writes  results.md, per_task.md, per_task_successes.csv, training_curves.md, analysis.json next to this script.

Definitions
  success        any-step success of an episode, as written by the official evaluator (n12/<task>.json "successes").
  rate           successes / 1200 (24 tasks x 50 episodes); CI = 95% Wilson interval of one run (episodes treated as
                 independent; it does not include checkpoint or simulator-seed variation).
  paired A -> B  episodes are paired by (task, episode index); every run uses environment seed 0 and policy noise seed 42.
                 net = (B succeeds, A fails) - (A succeeds, B fails); z = net / sqrt(number of discordant pairs)
                 (McNemar without continuity correction; |z| >= 1.96 is p < 0.05 two-sided, not corrected for the number
                 of comparisons in this file).
  block passes   action-expert block evaluations per policy query = steps x (3 pre + 6 x loops + 3 coda).
"""
import csv, gzip, json, math, time
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = HERE.parent
TEACHER = R.parent / "robocasa_gr1_continuation_20261108" / "eval"
SUFFIX, PREFIX = "_GR1ArmsAndWaistFourierHands_Env", "gr1_unified/"
PER = 47032
LOOPS, STEPS = (1, 2, 4), (2, 5, 10)
FLAT9 = [f"flat_k{k}_n{n}" for k in LOOPS for n in STEPS]
TIMING = {}


def label(s):
    k, n = (int(x[1:]) for x in s.split("_")[1:])
    return f"[{k},{k}]" if n == 2 else f"[{k}]x{n}"


def kn(s):
    return tuple(int(x[1:]) for x in s.split("_")[1:])


def passes(s):
    k, n = kn(s)
    return n * (6 + 6 * k)


def load(d):
    per = {}
    for f in sorted((d / "n12").glob("*.json")):
        x = json.loads(f.read_text())
        assert (x["seed"], x["n_episodes"], x["n_envs"], x["n_action_steps"], x["max_episode_steps"]) == (0, 50, 1, 12, 720), f
        assert len(x["successes"]) == 50 and x["server_metadata"]["noise_seed"] == 42, f
        per[x["env_name"].replace(PREFIX, "").replace(SUFFIX, "")] = [bool(s) for s in x["successes"]]
        TIMING.setdefault(str(d), []).append((x["client"]["queries"], x["client"]["mean_roundtrip_s"], x["wall_seconds"]))
    assert len(per) == 24, (d, len(per))
    return per


def timing(d):
    t = TIMING[str(d)]
    q = sum(x[0] for x in t)
    return dict(queries=q, mean_roundtrip_ms=round(1000 * sum(x[0] * x[1] for x in t) / q, 1), mean_task_wall_min=round(sum(x[2] for x in t) / len(t) / 60, 1))


def total(r):
    return sum(sum(v) for v in r.values())


def wilson(k, n, z=1.959963984540054):
    p = k / n
    c = p + z * z / (2 * n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (c - h) / (1 + z * z / n), (c + h) / (1 + z * z / n)


def paired(a, b):
    """a, b: lists of runs; run i of a is paired with run i of b."""
    n01 = n10 = 0
    for ra, rb in zip(a, b):
        assert sorted(ra) == sorted(rb)
        for t in ra:
            for x, y in zip(ra[t], rb[t]):
                n10 += x and not y
                n01 += y and not x
    return dict(net=n01 - n10, b_only=n01, a_only=n10, z=(n01 - n10) / math.sqrt(n01 + n10) if n01 + n10 else 0.0)


def pz(p):
    return f"{p['net']:+d} (z {p['z']:+.2f})"


def cnt(k, n=1200):
    return f"{k}/{n} ({100 * k / n:.2f}%)"


# ---------------------------------------------------------------- evidence
teacher = {e: load(TEACHER / f"official_epoch{e:02d}") for e in (9, 10)}
T = teacher[9]
TASKS = sorted(T)
runs, valid = {}, {}
for d in sorted((R / "eval").glob("e0?_flat_k*_n*")):
    if not d.is_dir():
        continue
    e, s = int(d.name[1:3]), d.name[4:]
    runs[(e, s)] = load(d)
    v = json.loads((R / "eval" / f"{d.name}_validation.json").read_text())
    assert v["successes"] == total(runs[(e, s)]) and v["episodes"] == 1200 and v["step"] == e * PER and v["schedule"] == s, d
    valid[(e, s)] = v
assert len(runs) == 25 and all(sorted(r) == TASKS for r in runs.values())
EPOCHS = sorted({e for e, _ in runs})
out = dict(teacher={str(e): total(r) for e, r in teacher.items()}, evaluations=[], grid={}, by_epoch={}, pooled={}, contrasts={})

# ---------------------------------------------------------------- results.md
L = ["# GR1-E0: evaluation tables", "",
     "Generated by `analyze_gr1_e0.py` from the per-episode files in `../eval` and the teacher's per-episode files in "
     "`../../robocasa_gr1_continuation_20261108/eval`. Definitions are in the script's header. Every evaluation is 24 tasks x 50 "
     "episodes = 1,200 episodes with the official protocol.", "",
     f"Teacher (GR1 v0 epoch 9, [4]x10, 300 block passes): **{cnt(total(T))}**; epoch 10: {cnt(total(teacher[10]))}; "
     f"teacher epoch 9 -> epoch 10 paired: {pz(paired([T], [teacher[10]]))}.", "",
     "## A. All 25 student evaluations", "",
     "| epoch | update | schedule | loops | steps | block passes | successes | 95% CI of the rate | paired vs teacher (net, z) | validator |",
     "|---|---|---|---|---|---|---|---|---|---|"]
for e in EPOCHS:
    for s in FLAT9:
        if (e, s) not in runs:
            continue
        r, v = runs[(e, s)], valid[(e, s)]
        k, n = kn(s)
        lo, hi = wilson(total(r), 1200)
        p = paired([T], [r])
        L.append(f"| {e} | {e * PER:,} | {label(s)} `{s}` | {k} | {n} | {passes(s)} | {cnt(total(r))} | {100 * lo:.1f}-{100 * hi:.1f}% | "
                 f"{pz(p)} | {'valid' if v['valid'] else 'flag (see README)'} |")
        out["evaluations"].append(dict(epoch=e, update=e * PER, schedule=s, label=label(s), loops=k, steps=n, block_passes=passes(s),
                                       successes=total(r), episodes=1200, percent=round(100 * total(r) / 1200, 4),
                                       ci95_percent=[round(100 * lo, 2), round(100 * hi, 2)], vs_teacher=p,
                                       validator_valid=v["valid"], validator_problems=v["problems"],
                                       export_sha256=v["export_sha256"]))
L += ["", "## B. All nine schedules, epochs 4 and 5", "",
      "| schedule | loops | steps | block passes | epoch 4 | vs teacher | epoch 5 | vs teacher | epoch 4 -> 5 |", "|---|---|---|---|---|---|---|---|---|"]
for s in FLAT9:
    a, b = runs[(4, s)], runs[(5, s)]
    k, n = kn(s)
    c = paired([a], [b])
    out["grid"][s] = dict(epoch4=total(a), epoch5=total(b), epoch4_to_5=c)
    L.append(f"| {label(s)} | {k} | {n} | {passes(s)} | {cnt(total(a))} | {pz(paired([T], [a]))} | {cnt(total(b))} | {pz(paired([T], [b]))} | {pz(c)} |")
for e in (4, 5):
    out["grid"][f"epoch{e}_all_nine"] = sum(total(runs[(e, s)]) for s in FLAT9)
c = paired([runs[(4, s)] for s in FLAT9], [runs[(5, s)] for s in FLAT9])
out["grid"]["all_nine_epoch4_to_5"] = c
L.append(f"| all nine | | | | {cnt(out['grid']['epoch4_all_nine'], 10800)} | | {cnt(out['grid']['epoch5_all_nine'], 10800)} | | {pz(c)} |")

L += ["", "## C. [1,1], [2,2] and [4,4] by epoch", "",
      "| schedule | epoch 1 | epoch 2 | epoch 3 | epoch 4 | epoch 5 |", "|---|---|---|---|---|---|"]
for s in ("flat_k1_n2", "flat_k2_n2", "flat_k4_n2"):
    L.append(f"| {label(s)} | " + " | ".join(cnt(total(runs[(e, s)])) if (e, s) in runs else "not evaluated" for e in EPOCHS) + " |")
    out["by_epoch"][s] = {str(e): total(runs[(e, s)]) for e in EPOCHS if (e, s) in runs}
L += ["", "Paired changes between epochs (net, z):", "", "| schedule | from -> to | net (z) |", "|---|---|---|"]
for s in ("flat_k1_n2", "flat_k2_n2", "flat_k4_n2"):
    es = [e for e in EPOCHS if (e, s) in runs]
    for i, a in enumerate(es):
        for b in es[i + 1:]:
            c = paired([runs[(a, s)]], [runs[(b, s)]])
            out["contrasts"][f"{s} epoch {a} -> {b}"] = c
            L.append(f"| {label(s)} | epoch {a} -> {b} | {pz(c)} |")
early, late = total(runs[(2, "flat_k4_n2")]) + total(runs[(3, "flat_k4_n2")]), total(runs[(4, "flat_k4_n2")]) + total(runs[(5, "flat_k4_n2")])
pp = (early + late) / 4800
zz = (late - early) / 2400 / math.sqrt(pp * (1 - pp) * 2 / 2400)
out["contrasts"]["[4,4] epochs 2+3 vs 4+5 (unpaired)"] = dict(early=early, late=late, episodes_each=2400, diff_points=round(100 * (late - early) / 2400, 4), z=zz)
L += ["", f"[4,4], epochs 2 and 3 pooled against epochs 4 and 5 pooled (unpaired two-proportion test): {cnt(early, 2400)} vs {cnt(late, 2400)}, "
          f"{100 * (late - early) / 2400:+.2f} points, z {zz:+.2f}."]

L += ["", "## D. Pooled by loop count and by step count (epochs 4 and 5)", "",
      "| epoch | 1 loop | 2 loops | 4 loops | loops 1 -> 2 | loops 2 -> 4 | 2 steps | 5 steps | 10 steps | steps 2 -> 5 | steps 5 -> 10 |",
      "|---|---|---|---|---|---|---|---|---|---|---|"]


def group(es, ks=LOOPS, ns=STEPS):
    return [runs[(e, f"flat_k{k}_n{n}")] for e in es for k in ks for n in ns]


for name, es in (("4", (4,)), ("5", (5,)), ("4 and 5", (4, 5))):
    n = 3600 * len(es)
    row = dict(episodes_per_cell=n)
    cells = []
    for k in LOOPS:
        row[f"loops_{k}"] = sum(map(total, group(es, (k,))))
        cells.append(cnt(row[f"loops_{k}"], n))
    for a, b in ((1, 2), (2, 4)):
        row[f"loops_{a}_to_{b}"] = paired(group(es, (a,)), group(es, (b,)))
        cells.append(pz(row[f"loops_{a}_to_{b}"]))
    for s in STEPS:
        row[f"steps_{s}"] = sum(map(total, group(es, LOOPS, (s,))))
        cells.append(cnt(row[f"steps_{s}"], n))
    for a, b in ((2, 5), (5, 10)):
        row[f"steps_{a}_to_{b}"] = paired(group(es, LOOPS, (a,)), group(es, LOOPS, (b,)))
        cells.append(pz(row[f"steps_{a}_to_{b}"]))
    out["pooled"][f"epoch {name}"] = row
    L.append(f"| {name} | " + " | ".join(cells) + " |")
L += ["", "Step count within each loop count (paired, net and z):", "", "| epoch | loops | steps 2 -> 5 | steps 5 -> 10 | steps 2 -> 10 |", "|---|---|---|---|---|"]
for e in (4, 5):
    for k in LOOPS:
        cells = []
        for a, b in ((2, 5), (5, 10), (2, 10)):
            c = paired([runs[(e, f"flat_k{k}_n{a}")]], [runs[(e, f"flat_k{k}_n{b}")]])
            out["contrasts"][f"epoch {e} loops {k} steps {a} -> {b}"] = c
            cells.append(pz(c))
        L.append(f"| {e} | {k} | " + " | ".join(cells) + " |")
L += ["", "Loop count at the same step count (paired, net and z):", "", "| epoch | steps | loops 1 -> 2 | loops 2 -> 4 | loops 1 -> 4 |", "|---|---|---|---|---|"]
for e in EPOCHS:
    for n in STEPS:
        if not all((e, f"flat_k{k}_n{n}") in runs for k in LOOPS):
            continue
        cells = []
        for a, b in ((1, 2), (2, 4), (1, 4)):
            c = paired([runs[(e, f"flat_k{a}_n{n}")]], [runs[(e, f"flat_k{b}_n{n}")]])
            out["contrasts"][f"epoch {e} steps {n} loops {a} -> {b}"] = c
            cells.append(pz(c))
        L.append(f"| {e} | {n} | " + " | ".join(cells) + " |")
L += ["", "## E. Policy round trip and wall time during the evaluations", "",
      "From the evaluation clients (`client.mean_roundtrip_s`, `wall_seconds` in each task file). The round trip is the time from sending an "
      "observation to receiving the action chunk, measured while 24 simulations share 8 policy servers on 4 GPUs, so it includes queueing and "
      "the network. It is **not** a single-query latency measurement; no such measurement exists for RoboCasa-GR1.", "",
      "| model | schedule | block passes | queries | mean round trip (ms) | mean wall time per task (min) |", "|---|---|---|---|---|---|"]
tt = timing(TEACHER / "official_epoch09")
out["timing"] = {"teacher epoch 9": tt}
L.append(f"| teacher epoch 9 | [4]x10 | 300 | {tt['queries']:,} | {tt['mean_roundtrip_ms']} | {tt['mean_task_wall_min']} |")
for e in (5, 4):
    for s in FLAT9:
        tt = timing(R / "eval" / f"e{e:02d}_{s}")
        out["timing"][f"epoch {e} {s}"] = tt
        L.append(f"| student epoch {e} | {label(s)} | {passes(s)} | {tt['queries']:,} | {tt['mean_roundtrip_ms']} | {tt['mean_task_wall_min']} |")
(HERE / "results.md").write_text("\n".join(L) + "\n")

# ---------------------------------------------------------------- per task
cols = [("teacher e9", T), ("teacher e10", teacher[10])] + [(f"e{e} {label(s)}", runs[(e, s)]) for e in EPOCHS for s in FLAT9 if (e, s) in runs]
with open(HERE / "per_task_successes.csv", "w", newline="") as f:
    w = csv.writer(f, lineterminator="\n")
    w.writerow(["task"] + [c for c, _ in cols])
    for t in TASKS:
        w.writerow([t] + [sum(r[t]) for _, r in cols])
    w.writerow(["TOTAL (of 1200)"] + [total(r) for _, r in cols])
P = ["# GR1-E0: successes per task (of 50 episodes)", "",
     "Generated by `analyze_gr1_e0.py`. All 25 evaluations and both teacher epochs are in `per_task_successes.csv`.", ""]
for e in (5, 4):
    P += [f"## Epoch {e}, all nine schedules", "", "| task | teacher | " + " | ".join(label(s) for s in FLAT9) + " |", "|---|---|" + "---|" * 9]
    for t in TASKS:
        P.append(f"| {t} | {sum(T[t])} | " + " | ".join(str(sum(runs[(e, s)][t])) for s in FLAT9) + " |")
    P += [f"| **total (of 1200)** | {total(T)} | " + " | ".join(str(total(runs[(e, s)])) for s in FLAT9) + " |", ""]
P += ["## [1,1] by epoch", "", "| task | teacher | " + " | ".join(f"epoch {e}" for e in EPOCHS) + " |", "|---|---|" + "---|" * len(EPOCHS)]
for t in TASKS:
    P.append(f"| {t} | {sum(T[t])} | " + " | ".join(str(sum(runs[(e, 'flat_k1_n2')][t])) for e in EPOCHS) + " |")
P.append(f"| **total (of 1200)** | {total(T)} | " + " | ".join(str(total(runs[(e, 'flat_k1_n2')])) for e in EPOCHS) + " |")
below = sum(sum(sum(runs[(e, "flat_k1_n2")][t]) for e in (2, 3, 4, 5)) / 4 < sum(T[t]) for t in TASKS)
out["tasks_where_mean_11_epochs_2_to_5_below_teacher"] = below
P += ["", f"Tasks where the mean [1,1] count of epochs 2-5 is below the teacher's: {below} of 24."]
(HERE / "per_task.md").write_text("\n".join(P) + "\n")

# ---------------------------------------------------------------- training
acc, n_sched, secs, lr_end, first_time, last_time = {}, {}, {e: 0.0 for e in range(1, 6)}, {}, {}, {}
count, prev, prev_time, gaps, peak, werr = 0, 0, 0.0, [], 0.0, 0.0
with gzip.open(R / "training" / "metrics.jsonl.gz", "rt") as f:
    for line in f:
        r = json.loads(line)
        u, e = r["update"], r["epoch"]
        assert u == prev + 1 and e == (u - 1) // PER + 1, u
        if prev and r["time"] - prev_time > 600:
            gaps.append(dict(after_update=prev, paused_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(prev_time)), seconds=round(r["time"] - prev_time), resumed_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(r["time"]))))
        prev, prev_time = u, r["time"]
        peak = max(peak, r["peak_allocated_gb"])
        werr = max(werr, abs(r["total"] - (r["local"] + 0.5 * r["end"] + 0.5 * r["anchor"])))
        assert r["grip"] == 0.0
        count += 1
        secs[e] += r["seconds"]
        first_time.setdefault(e, r["time"]); last_time[e] = r["time"]
        n_sched[r["schedule"]] = n_sched.get(r["schedule"], 0) + 1
        if u > e * PER - 6000:
            a = acc.setdefault((e, r["schedule"]), [0, 0.0, 0.0, 0.0])
            a[0] += 1; a[1] += r["end"]; a[2] += r["local"]; a[3] += r["anchor"]
        if u % PER == 0:
            lr_end[e] = r["lr"]
assert count == prev == 5 * PER
launches = [json.loads(l) for l in (R / "training" / "launches.jsonl").read_text().splitlines()]
tr = dict(updates=count, updates_per_epoch=PER, launches=len(launches), updates_per_schedule=n_sched,
          seconds_in_updates={str(e): round(v, 1) for e, v in secs.items()}, hours_in_updates=round(sum(secs.values()) / 3600, 2),
          pauses_over_10_min=gaps, peak_allocated_gb=round(peak, 2), max_abs_total_minus_weighted_sum=werr,
          lr_at_epoch_end={str(e): dict(step_condition=v[0], action_expert=v[1]) for e, v in lr_end.items()}, loss_last_6000={})
C = ["# GR1-E0: training record", "", "Generated by `analyze_gr1_e0.py` from `../training/metrics.jsonl.gz` (one row per update) and `../training/launches.jsonl`.", "",
     f"- Updates: {count:,} = 5 epochs x {PER:,}, each update recorded once, in order. Launches: {len(launches)} "
     f"({', '.join(l['time'] for l in launches)}).",
     f"- Time inside updates (sum of `seconds`): " + ", ".join(f"epoch {e} {secs[e] / 3600:.2f} h" for e in range(1, 6)) + f"; total {sum(secs.values()) / 3600:.2f} h; "
     f"mean {sum(secs.values()) / count:.3f} s per update.",
     f"- Updates per schedule: " + ", ".join(f"{label(s)} {n_sched[s]:,}" for s in FLAT9) + ".",
     f"- Loss: `total` = `local` + 0.5 x `end` + 0.5 x `anchor` in every row (largest absolute difference {werr:.1e}); `grip` is 0 in every row. "
     f"Peak allocated GPU memory: {peak:.1f} GB.",
     "- Pauses longer than 10 minutes between consecutive updates (evaluations after epochs 1-4, and the stop inside epoch 5): "
     + "; ".join(f"after update {g['after_update']:,} ({g['paused_utc']}): {g['seconds'] / 3600:.2f} h, resumed {g['resumed_utc']}" for g in gaps) + ".",
     "- Learning rate at the end of each epoch (action expert / step condition): " + "; ".join(f"epoch {e} {lr_end[e][1]:.3g} / {lr_end[e][0]:.3g}" for e in range(1, 6)) + ".", ""]
for key, idx, title in (("end", 1, "Endpoint loss `end` (MSE between the student's and the teacher's first 12 actions, normalized units)"),
                        ("local", 2, "Local loss `local` (velocity matching, mean over the schedule's steps)")):
    C += [f"## {title}", "", "Mean over the last 6,000 updates of each epoch, per schedule (about 667 updates per cell).", "",
          "| epoch | " + " | ".join(label(s) for s in FLAT9) + " |", "|---|" + "---|" * 9]
    for e in range(1, 6):
        C.append(f"| {e} | " + " | ".join(f"{acc[(e, s)][idx] / acc[(e, s)][0]:.5f}" for s in FLAT9) + " |")
        tr["loss_last_6000"].setdefault(key, {})[str(e)] = {s: acc[(e, s)][idx] / acc[(e, s)][0] for s in FLAT9}
    C.append("")
out["training"] = tr
(HERE / "training_curves.md").write_text("\n".join(C) + "\n")
(HERE / "analysis.json").write_text(json.dumps(out, indent=1) + "\n")
print("teacher", out["teacher"], "| evaluations", len(out["evaluations"]), "| epoch 4/5 all nine", out["grid"]["epoch4_all_nine"], out["grid"]["epoch5_all_nine"],
      "| training updates", count, "hours", tr["hours_in_updates"])
