#!/usr/bin/env bash
# Copy the public-WAM latency artifacts (released models only) into the LoopWAM_elastic worktree (branch elastic),
# regenerate the report, and commit locally. Pushing is done separately. Usage: finalize_to_repo.sh "<commit message>"
set -e
LAT=/groups/yshang/an221229/checkpoints/wam_baselines/latency
W=/lustre/fs1/home/an221229/code/LoopWAM_elastic
PL=$W/plans/performance/public_wam_latency_20261030
PY=/groups/yshang/an221229/envs/FastWAM/bin/python
mkdir -p $PL/results $PL/logs
for m in fastwam fastwam_nocompile fasterwam lightwam lilawam; do
  for f in $LAT/results/${m}_evc10?.json $LAT/results/${m}_evc10?.config.yaml; do
    [ -f "$f" ] && cp "$f" $PL/results/
  done
done
cp $LAT/measure_public_latency.py $LAT/measure_lilawam_latency.py $LAT/run_models.sh $LAT/run_lilawam.sh \
   $LAT/run_official_fasterwam.sh $LAT/env.sh $LAT/build_tables.py $LAT/make_report.py $LAT/report_v2_template.md \
   $LAT/finalize_to_repo.sh $LAT/checkpoint_sha256.json $PL/
cp $LAT/logs/node_evc10?.log $PL/logs/ 2>/dev/null || true
cd /tmp && $PY $LAT/make_report.py $W/plans/performance/Public_WAM_Latency_20261030.md
cd $W
git add -A plans/performance/Public_WAM_Latency_20261030.md plans/performance/public_wam_latency_20261030
if git diff --cached | grep -qE "ghp_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|hf_[A-Za-z0-9]{30,}"; then echo "SECRET FOUND - abort"; git reset -q; exit 3; fi
git diff --cached --stat | tail -n 1
git commit -q -F - <<MSG
$1

Report: plans/performance/Public_WAM_Latency_20261030.md (generated by make_report.py from the result files).

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>
MSG
git log --oneline -1
