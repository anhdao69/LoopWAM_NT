#!/usr/bin/env bash
# Copy latency + LiLa-WAM training artifacts into the LoopWAM_elastic worktree (branch elastic), regenerate the report,
# and commit locally. Pushing is done separately. Usage: finalize_to_repo.sh "<commit message first line>"
set -e
LAT=/groups/yshang/an221229/checkpoints/wam_baselines/latency
LILA=/groups/yshang/an221229/checkpoints/wam_baselines/lilawam
RUN=$LILA/libero_ours_paper_recipe
CODE=/groups/yshang/an221229/code/lilawam_libero
W=/lustre/fs1/home/an221229/code/LoopWAM_elastic
PL=$W/plans/performance/public_wam_latency_20261030
PT=$W/plans/performance/lilawam_libero_20261030
PY=/groups/yshang/an221229/envs/FastWAM/bin/python
mkdir -p $PL/results $PT/configs $PT/logs $PT/openloop $PT/upload
# latency
cp $LAT/results/*.json $LAT/results/*.yaml $PL/results/ 2>/dev/null || true
rm -f $PL/results/*smoke*
cp $LAT/measure_public_latency.py $LAT/measure_lilawam_latency.py $LAT/measure_lilawam_libero_latency.py \
   $LAT/run_models.sh $LAT/run_lilawam.sh $LAT/run_official_fasterwam.sh $LAT/env.sh $LAT/build_tables.py \
   $LAT/make_report.py $LAT/report_v2_template.md $LAT/finalize_to_repo.sh $LAT/checkpoint_sha256.json $PL/
# LiLa-WAM training
cp $CODE/*.py $CODE/libero_ours.yaml $LILA/convert_ours_to_lilawam_hdf5.py $LILA/verify_conversion.py \
   $LILA/conversion_verification.json $RUN/train_job.sh $RUN/hf_upload_watcher.py $RUN/openloop_watcher.sh $RUN/HANDOFF.md $PT/
cp $RUN/hf_staging/README.md $PT/HF_MODEL_CARD.md
cp $RUN/configs/*.yaml $PT/configs/
cp /groups/yshang/an221229/data/LiLaWAM_libero_ours_stats*.json /groups/yshang/an221229/data/LiLaWAM_libero_ours_taskcond/meta.json $PT/configs/ 2>/dev/null || true
mv -f $PT/configs/meta.json $PT/configs/task_cond_meta.json 2>/dev/null || true
cp $RUN/train_job.log $PT/logs/
cp $RUN/logs/*.log $PT/logs/ 2>/dev/null || true
for s in libero_10 libero_goal libero_object libero_spatial; do
  for c in $RUN/$s/log/loss/*.csv; do [ -f "$c" ] && cp "$c" "$PT/logs/${s}_$(basename $c)"; done
done
cp $RUN/openloop/*.json $RUN/openloop/watcher.log $PT/openloop/ 2>/dev/null || true
cp $RUN/manifest.json $RUN/uploaded_*.json $RUN/hf_upload_watcher.log $PT/upload/ 2>/dev/null || true
rm -f $PT/libero_ours_stats*.json
# report
cd /tmp && $PY $LAT/make_report.py $W/plans/performance/Public_WAM_Latency_20261030.md
cd $W
git add -f plans/performance/Public_WAM_Latency_20261030.md plans/performance/public_wam_latency_20261030 plans/performance/lilawam_libero_20261030
if git diff --cached | grep -qE "ghp_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|hf_[A-Za-z0-9]{30,}"; then echo "SECRET FOUND - abort"; git reset -q; exit 3; fi
git diff --cached --stat | tail -n 1
git commit -q -F - <<MSG
$1

Report: plans/performance/Public_WAM_Latency_20261030.md (generated by make_report.py from the result files).

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>
MSG
git log --oneline -1
